#!/usr/bin/env bash
# Reproducible customer deployment: preflight -> SAM -> outputs -> SPA -> verify.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

PREFLIGHT_ARGS=()
for arg in "$@"; do
  case "$arg" in
    --allow-cognito-only|--allow-expiration) PREFLIGHT_ARGS+=("$arg") ;;
    -h|--help)
      echo "Uso: $0 [--allow-cognito-only] [--allow-expiration]"
      exit 0 ;;
    *) echo "ERROR: opción desconocida: $arg" >&2; exit 2 ;;
  esac
done

"${SCRIPT_DIR}/preflight.sh" "${PREFLIGHT_ARGS[@]}"
load_deploy_env

echo
echo "== 1/5 Infraestructura AWS =="
"${REPO_ROOT}/infra/deploy.sh"

echo
echo "== 2/5 Outputs del stack =="
VIDEO_BUCKET="$(stack_output VideoBucketName)"
SPA_BUCKET="$(stack_output SpaBucketName)"
USER_POOL="$(stack_output UserPoolId)"
CLIENT_ID="$(stack_output UserPoolClientId)"
API_ENDPOINT="$(stack_output ApiEndpoint)"
CLOUDFRONT_URL="$(stack_output CloudFrontUrl)"
DISTRIBUTION_ID="$(stack_output CloudFrontDistributionId)"
HOSTED_UI="$(stack_output HostedUiDomain)"
UPLOADER_ROLE_ARN="$(stack_output UploaderRoleArn)"

for pair in \
  "VideoBucketName=${VIDEO_BUCKET}" "SpaBucketName=${SPA_BUCKET}" \
  "UserPoolId=${USER_POOL}" "UserPoolClientId=${CLIENT_ID}" \
  "ApiEndpoint=${API_ENDPOINT}" "CloudFrontUrl=${CLOUDFRONT_URL}" \
  "CloudFrontDistributionId=${DISTRIBUTION_ID}" "HostedUiDomain=${HOSTED_UI}" \
  "UploaderRoleArn=${UPLOADER_ROLE_ARN}"; do
  key="${pair%%=*}"; value="${pair#*=}"
  [[ -n "${value}" && "${value}" != "None" ]] || {
    echo "ERROR: output ${key} ausente." >&2
    exit 1
  }
done

upsert_env_values "${ENV_FILE}" \
  "VIDEO_BUCKET_RESOLVED=${VIDEO_BUCKET}" \
  "SPA_BUCKET_RESOLVED=${SPA_BUCKET}" \
  "COGNITO_USER_POOL_ID=${USER_POOL}" \
  "COGNITO_USER_POOL_CLIENT_ID=${CLIENT_ID}" \
  "CLOUDFRONT_URL=${CLOUDFRONT_URL}" \
  "CLOUDFRONT_DISTRIBUTION_ID=${DISTRIBUTION_ID}" \
  "COGNITO_HOSTED_UI_DOMAIN=${HOSTED_UI}" \
  "UPLOADER_ROLE_ARN=${UPLOADER_ROLE_ARN}"

echo "  Video bucket : ${VIDEO_BUCKET}"
echo "  SPA bucket   : ${SPA_BUCKET}"
echo "  Web URL      : ${CLOUDFRONT_URL}"
echo "  Uploader role: ${UPLOADER_ROLE_ARN}"

echo
echo "== 3/5 Configuración y build del frontend =="
cat > "${REPO_ROOT}/frontend/.env.production" <<EOF
# Generated by scripts/deploy-customer.sh. Local, git-ignored, no secrets.
VITE_API_BASE=/v1
VITE_HOSTED_UI_DOMAIN=${HOSTED_UI}
VITE_COGNITO_CLIENT_ID=${CLIENT_ID}
VITE_COGNITO_USER_POOL_ID=${USER_POOL}
VITE_REDIRECT_URI=${CLOUDFRONT_URL}/
EOF
(
  cd "${REPO_ROOT}/frontend"
  npm ci
  npm audit --omit=dev
  npm run typecheck
  npm run test
  npm run build
)

echo
echo "== 4/5 Publicación de la SPA =="
aws s3 sync "${REPO_ROOT}/frontend/dist/" "s3://${SPA_BUCKET}/" \
  --delete "${AWS_ARGS[@]}"
aws cloudfront create-invalidation \
  --distribution-id "${DISTRIBUTION_ID}" \
  --paths '/*' --profile "${AWS_PROFILE_VALUE}" >/dev/null
echo "  SPA publicada; invalidación solicitada."

echo
echo "== 5/5 Verificación =="
"${SCRIPT_DIR}/verify-deployment.sh"

echo
echo "Deployment completo: ${CLOUDFRONT_URL}/"
echo "Siguiente paso: scripts/create-user.sh <email-del-operador>"
